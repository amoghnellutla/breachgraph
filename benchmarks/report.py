"""Build docs/benchmark.md from benchmarks/results/*.json and the hand labels in benchmarks/labels/.

    python benchmarks/report.py           # write docs/benchmark.md
    python benchmarks/report.py --check   # fail if any reported path is unlabeled or the doc is stale

Every attack path breachgraph reports must carry a label: true (a real chain an attacker could
use, given the project's documented scenario), false (not a real chain), or unclear. Precision is
true / (true + false). Misses are documented scenarios breachgraph should have found but didn't.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
BENCH = ROOT / "benchmarks"
DOC = ROOT / "docs" / "benchmark.md"
VERDICTS = ("true", "false", "unclear")


def load() -> list[tuple[dict[str, Any], dict[str, Any], dict[str, Any]]]:
    targets = yaml.safe_load((BENCH / "targets.yml").read_text(encoding="utf-8"))
    rows = []
    for t in targets:
        result_file = BENCH / "results" / f"{t['name']}.json"
        if not result_file.is_file():
            continue
        result = json.loads(result_file.read_text(encoding="utf-8"))
        label_file = BENCH / "labels" / f"{t['name']}.yml"
        labels = yaml.safe_load(label_file.read_text(encoding="utf-8")) if label_file.is_file() else {}
        rows.append((t, result, labels or {}))
    return rows


def verdicts(result: dict[str, Any], labels: dict[str, Any]) -> tuple[dict[str, str], list[str]]:
    """{path key: verdict} for every reported path, and the keys nobody labeled yet."""
    # YAML reads `verdict: true` as a boolean; compare as lowercase text.
    by_key = {str(p["key"]): str(p["verdict"]).lower() for p in labels.get("paths") or []}
    unlabeled = [p["key"] for p in result["attack_paths"] if by_key.get(p["key"]) not in VERDICTS]
    return {p["key"]: by_key.get(p["key"], "unlabeled") for p in result["attack_paths"]}, unlabeled


def _pct(a: int, b: int) -> str:
    return f"{100 * a / b:.0f}%" if b else "n/a"


def render(rows: list[tuple[dict[str, Any], dict[str, Any], dict[str, Any]]]) -> str:
    total = {"raw": 0, "findings": 0, "gating": 0, "paths": 0, "true": 0, "false": 0, "unclear": 0}
    chains = misses = 0  # true paths that needed at least one weakness; documented misses
    lines = [
        "# Benchmark: breachgraph on real projects",
        "",
        "<!-- Generated by benchmarks/report.py from benchmarks/results and benchmarks/labels. Do not edit. -->",
        "",
        "breachgraph was run, unchanged and with default settings, on intentionally vulnerable",
        "training projects (where real attack chains are documented) and on one well-maintained",
        "production-style project as a noise control. Every attack path it reported was reviewed by",
        "hand against the project's documented scenarios and labeled **true** (a real chain),",
        "**false** (not a real chain) or **unclear**. Scenarios it should have found but didn't are",
        "listed as misses.",
        "",
        "| Project | Kind | Scanner findings | After dedupe | Blocking findings | Attack paths | True | False | Unclear |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    details: list[str] = []
    for target, result, labels in rows:
        v, _unlabeled = verdicts(result, labels)
        counts = {k: sum(1 for x in v.values() if x == k) for k in VERDICTS}
        total["raw"] += result["raw_findings"]
        total["findings"] += result["findings"]
        total["gating"] += result["gating_findings"]
        total["paths"] += len(result["attack_paths"])
        for k in VERDICTS:
            total[k] += counts[k]
        chains += sum(1 for p in result["attack_paths"] if p["weapons"] and v[p["key"]] == "true")
        misses += len(labels.get("misses") or [])
        lines.append(
            f"| [{target['name']}]({target['repo']}) | {target['kind']} | {result['raw_findings']:,} | "
            f"{result['findings']:,} | {result['gating_findings']:,} | {len(result['attack_paths'])} | "
            f"{counts['true']} | {counts['false']} | {counts['unclear']} |"
        )
        details += [f"### {target['name']}", "", f"{target['covers']}. Commit `{target['sha'][:12]}`.", ""]
        if labels.get("summary"):
            details += [str(labels["summary"]).strip(), ""]
        for p in result["attack_paths"]:
            label = next((x for x in labels.get("paths") or [] if x["key"] == p["key"]), {})
            details.append(f"- **{v[p['key']]}** · {p['confidence']} confidence · `{p['key']}`")
            if label.get("why"):
                details.append(f"  {str(label['why']).strip()}")
        if not result["attack_paths"]:
            details.append("- No attack paths reported.")
        for miss in labels.get("misses") or []:
            details.append(
                f"- **miss**: {str(miss['scenario']).strip()} {str(miss.get('why', '')).strip()}".rstrip()
            )
        details.append("")
    decided = total["true"] + total["false"]
    lines += [
        f"| **Total** | | **{total['raw']:,}** | **{total['findings']:,}** | **{total['gating']:,}** | "
        f"**{total['paths']}** | **{total['true']}** | **{total['false']}** | **{total['unclear']}** |",
        "",
        f"**Path precision: {_pct(total['true'], decided)}** ({total['true']} of {decided} decided paths are real "
        f"attack chains). {total['findings']:,} deduplicated findings reduce to **{total['paths']} attack paths** "
        "to review first.",
        "",
        f"Of the {total['true']} real paths, {total['true'] - chains} are direct exposures of data (a public bucket, "
        f"dataset or storage account) and {chains} {'is a chain' if chains == 1 else 'are chains'} that needed a code "
        f"vulnerability to cross into the cloud. {misses} documented scenarios were not found as complete paths; "
        "each is listed below with the reason, and most start from something breachgraph does not model as an entry "
        "point (credentials handed to the player, a port-forwarded lab, a leaked SSH key).",
        "",
        "## Per project",
        "",
        *details,
        "## Reproduce",
        "",
        "```bash",
        "docker build -t breachgraph:dev .",
        "python benchmarks/run.py           # clones each project at its pinned commit and scans it",
        "python benchmarks/report.py        # rebuilds this page from results/ and labels/",
        "```",
        "",
        "Run with breachgraph at commit "
        + ", ".join(sorted({f"`{r.get('breachgraph_commit', 'unknown')}`" for _t, r, _l in rows}))
        + ". "
        "Scanner versions are recorded per run in `benchmarks/results/`.",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    opts = ap.parse_args()
    rows = load()
    missing = [(t["name"], k) for t, r, labels in rows for k in verdicts(r, labels)[1]]
    for name, key in missing:
        print(f"unlabeled path in {name}: {key}")
    text = render(rows)
    if opts.check:
        stale = not DOC.is_file() or DOC.read_text(encoding="utf-8") != text
        if stale:
            print("docs/benchmark.md is stale: run python benchmarks/report.py")
        return 1 if missing or stale else 0
    if missing:
        return 1
    DOC.write_text(text, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
